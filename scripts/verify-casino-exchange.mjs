import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const context = vm.createContext({});
for (const path of ['bundle/umi-arcade-rules.js', 'bundle/casino-exchange-ui.js']) vm.runInContext(readFileSync(new URL('../' + path, import.meta.url), 'utf8'), context);
const items = context.UmiArcadeRules.ITEMS, ui = context.UmiCasinoExchangeUI;
const esc = value => String(value ?? '').replace(/[&<>"']/g, char => ({ '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;' }[char]));
const helpers = { items, esc, fmt: value => Number(value || 0).toLocaleString('vi-VN'), img: src => `<img src="${esc(src)}">`, button: (label, action, data, disabled) => `<button data-action="${action}" ${data}${disabled ? ' disabled' : ''}>${label}</button>` };
const snapshot = { state: { scrap: 123, goal: 'umi-mega-selector', items: { 'umi-spin-ticket': 3 } } };
const initial = JSON.stringify(snapshot);
let html = ui.render(snapshot, helpers);
assert.equal((html.match(/class="ux-entry/g) || []).length, 12);
assert(html.includes('Còn thiếu 2.377 mảnh'));
assert(html.includes('Đang có 3'));
ui.setFilter('affordable'); html = ui.render(snapshot, helpers);
assert.equal((html.match(/class="ux-entry/g) || []).length, 2, 'Affordable filter must include only the 100 and 120 fragment rewards');
assert(html.includes('Đổi Vé quay miễn phí với 100 mảnh'));
ui.setFilter('evolution'); html = ui.render(snapshot, helpers);
assert.equal((html.match(/class="ux-entry/g) || []).length, 3);
ui.setFilter('invalid'); assert.equal(ui.render(snapshot, helpers), html, 'Unknown filter changed the view');
ui.setFilter('affordable'); snapshot.state.scrap = 0;
assert(ui.render(snapshot, helpers).includes('Chưa đủ mảnh để đổi quà.'));
snapshot.state.scrap = 123;
assert.equal(JSON.stringify(snapshot), initial, 'Rendering or filtering changed saved game state');
const htmlSource = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
assert(!/casino-(?:batch|native)\.js/.test(htmlSource), 'Removed spin package still loaded');
assert(!/UmiCasinoBatch|UmiCasinoNative|UmiCasinoBridge/.test(readFileSync(new URL('../bundle/umi-arcade.js', import.meta.url), 'utf8')));
console.log('Casino exchange passed: catalogue, affordability, goals, filters, empty state, save isolation and removed package wiring.');
